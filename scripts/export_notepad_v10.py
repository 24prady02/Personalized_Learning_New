"""
export_notepad_v10.py — one plain-text report (opens in Notepad) of the earlier run that produced the
100 classified scenarios: output/scenario_run_v10_all (NLI + LLM judge fusion, old judge prompt).

For each of the 100 scenarios in output/selected_100/classify_100_classified.xlsx it writes every
intermediate output of the algorithm, the final level, and the concept map as it was formed (the
nodes in students/<id>.json and the graph edges between them).

Usage: python scripts/export_notepad_v10.py
Writes output/scenario_run_v10_all/LP_v10_100_scenarios.txt.
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import openpyxl  # noqa: E402

import export_notepad_100 as ex  # noqa: E402  (shared helpers: wrap, link_parts, closest_rule, level_logic)
from run_student_scenarios import asked_part  # noqa: E402
from src.lp_percpt import judge as judgelib  # noqa: E402
from src.lp_percpt.evidence import asks_beyond  # noqa: E402
from src.lp_percpt.identify import split_clauses  # noqa: E402
from src.lp_percpt.thresholds import KEEP_SCORE, MAX_CONCEPTS, RELATIVE_KEEP  # noqa: E402

os.environ.pop("LP_JUDGE_PROMPT", None)   # this run used the original judge prompt (with boundaries)
RUN = ROOT / "output" / "scenario_run_v10_all"
LV = ["L0", "L1", "L2", "L3", "L4", "none"]
W = ex.W
wrap = ex.wrap
LEVEL_INT = {0: "L0", 1: "L1", 2: "L2", 3: "L3", 4: "L4"}


def labels():
    ws = openpyxl.load_workbook(ROOT / "output" / "selected_100" / "classify_100_classified.xlsx",
                                read_only=True)["Classify 100"]
    return {r[0]: str(r[5]).strip() for r in ws.iter_rows(values_only=True)
            if r[0] and str(r[0]).startswith("S") and len(str(r[0])) < 6}


def node_level(v):
    return LEVEL_INT.get(v, v) if v is not None else "-"


def main() -> None:
    ref = labels()
    res = {s["id"]: s for s in json.loads((RUN / "results.json").read_text(encoding="utf-8"))["scenarios"]}
    g = json.loads((ROOT / "data" / "chapter1_kg.json").read_text(encoding="utf-8"))
    edges = g["edges"]
    pair_edges = defaultdict(list)
    for e in edges:
        if e["type"] in ("prerequisite", "parallel"):
            pair_edges[frozenset((e["source"], e["target"]))].append(e)
    ids = [i for i in ref if i in res]
    final = {i: res[i]["max_level"] or "none" for i in ids}

    out = ["LP CLASSIFIER - THE EARLIER RUN OF THE 100 SCENARIOS (scenario_run_v10_all)",
           "Every intermediate output of the algorithm, the final level, and the concept map formed, per scenario",
           f"Run folder: output/scenario_run_v10_all   Graph: {g['version']}"]

    # accuracy
    body = []
    ex.h1(body, "1. Level accuracy of this run")
    k = sum(final[i] == ref[i] for i in ids)
    per, hit = Counter(ref[i] for i in ids), Counter(ref[i] for i in ids if final[i] == ref[i])
    pairs = [(int(ref[i][1]), int(final[i][1])) for i in ids if "none" not in (ref[i], final[i])]
    body += [f"Exact match with classify_100_classified.xlsx : {k}/{len(ids)} ({k / len(ids):.0%})",
             f"Within one level (both sides levelled)        : {sum(abs(a - b) <= 1 for a, b in pairs)}/{len(pairs)}",
             "Per classified level (correct / answers):"]
    body += [f"    {x:5s} {hit[x]:3d} / {per[x]}" for x in LV]
    body += ["", "Label source: the classified levels were generated by an LLM; no human levels are used."]

    # algorithm as it ran
    ex.h1(body, "2. The algorithm as it ran in this session")
    steps = [
        ("Gates", "help_seeking (asks only for the answer) or content (too few words) stop the answer early. "
                  "There was no no-claim check in this run."),
        ("A  Concept map",
         "A1 clauses -> A2-A4 link score per concept (code cues, cue in the question part, word cues, meaning "
         "similarity, misconception-edge similarity) -> A5 keep rule (score >= 1.0 and >= half the best, at most 3) "
         "-> A6 one extra concept for the judge -> A7 placement on the graph (prerequisite / parallel edges) -> "
         "A8 the NODES FORMED in the student's concept map (students/<id>.json): one node per assessed concept "
         "with its level, evidence E1-E4, misconceptions held and stop reason."),
        ("B  Level",
         "B1 gates -> B2 graph evidence per concept: clause -> graph statement, matched by MiniLM similarity and "
         "the NLI model (on in this run), checks E1-E4 -> B3 code run -> B4 rule level per concept (the ladder "
         "walk over E1-E4, stored on the node) -> B5 LLM judge (original prompt: per-concept levels only, no "
         "overall level) -> B6 fusion per concept: a wrong rule found by the code run or the judge is L0; a level "
         "set by the code run or the question-form rules stands; a level set by a weak reader (NLI, relation "
         "cue, similarity fact) is replaced by the judge's -> B7 answer level: L0 if any concept holds a wrong "
         "rule, else the highest concept level."),
    ]
    for t, d in steps:
        body += ["", "  " + t, wrap(d, "      ")]
    body += ["", "  Judge system prompt used in this run (verbatim):"]
    body += ["    " + line for line in judgelib.SYSTEM.splitlines()]

    # per scenario
    ex.h1(body, "3. Every scenario: intermediate outputs, final level, concept map formed")
    for i in ids:
        s = res[i]
        body += scenario(s, ref[i], pair_edges, edges)

    ex.h1(body, "4. Files")
    body += ["  output/scenario_run_v10_all/results.json     everything the engine returned (all 365 scenarios)",
             "  output/scenario_run_v10_all/students/<id>.json  the concept-map nodes formed per student",
             "  output/scenario_run_v10_all/maps/<id>.html      the concept map drawn per student",
             "  Rebuild this file: python scripts/export_notepad_v10.py"]

    lines = "\n".join(body).split("\n")
    idx_head = ["", "=" * W, "INDEX - ALL 100 SCENARIOS (line where each scenario starts; Ctrl+G in Notepad)", "=" * W,
                f"  {'ID':6s} {'line':>6s}   final   classified"]
    n_idx = len(idx_head) + len(ids) + 1
    start = {ln.split()[1]: j + 1 + len(out) + n_idx for j, ln in enumerate(lines) if ln.startswith("SCENARIO S")}
    idx = idx_head + [f"  {sid:6s} {start[sid]:6d}   {final[sid]:5s}   {ref[sid]}" for sid in ids] + [""]
    text = out + idx + lines
    path = RUN / "LP_v10_100_scenarios.txt"
    path.write_text("\n".join(text) + "\n", encoding="utf-8-sig")
    print("wrote", path, f"({len(text)} lines)")


def scenario(s, label, pair_edges, edges):
    o = []
    sid = s["id"]
    asked = asked_part(s.get("question_text", ""), s.get("scenario_type", ""))
    code = s.get("code", "") or ""
    o += ["", "#" * W, f"SCENARIO {sid}", "#" * W,
          wrap("Question part: " + (asked or s.get("question_text", "") + "  (whole question; no part named)"), "  "),
          wrap("Code: " + ((code[:300] + (" ..." if len(code) > 300 else "")) if code else "(none)"), "  "),
          wrap("Answer: " + s["text"], "  ")]
    linked = [c for c in s["concepts"] if "judge_only" not in (c.get("gates") or [])]
    extra = [c for c in s["concepts"] if "judge_only" in (c.get("gates") or [])]
    student = json.loads((RUN / "students" / f"{s['student']}.json").read_text(encoding="utf-8"))
    nodes = student.get("nodes", {})

    # A concept map
    o += ["", "  WORKFLOW A - CONCEPT MAP"]
    o.append("    A1  clauses:")
    o += [wrap(f"({k + 1}) {c}", "          ") for k, c in enumerate(split_clauses(s["text"]))]
    det = ex.link_detail(s["text"], code, asked)
    best = max((h.score for h in det.values()), default=0.0)
    o.append("    A2-A4  link score per concept (cue, meaning and misconception-edge matching):")
    for c in linked:
        cc, sc = c["concept"], c.get("link_score") or 0
        h = det.get(cc)
        o.append(f"          [{cc}]  link score {sc}")
        if h is None:
            continue
        for name, pts, what in ex.link_parts(h, cc, s["text"], code, asked):
            if pts or (what and "below" not in what and name.startswith(("meaning", "misconception"))):
                o.append(wrap(f"+ {pts:.2f}  {name}" + (f": {what}" if what else ""), "              "))
    o.append(wrap(f"A5  keep rule: score >= {KEEP_SCORE} and >= {RELATIVE_KEEP} x best ({best:.2f}), at most "
                  f"{MAX_CONCEPTS} -> LINKED: " + (", ".join(c["concept"] for c in linked) or "none"), "    "))
    if extra:
        for c in extra:
            b = ex.closest_rule(s["text"], c["concept"])
            t = f"A6  extra concept for the judge: {c['concept']}"
            if b:
                (lv, wn, rule), sim = b
                t += f", its {lv} way '{wn}' is closest (cosine {sim:.3f}): \"{rule}\""
            o.append(wrap(t, "    "))
    else:
        o.append("    A6  extra concept for the judge: none")
    names = [c["concept"] for c in linked] + [c["concept"] for c in extra]
    o.append("    A7  graph edges between these concepts:")
    found = [e for a_i, a in enumerate(names) for b in names[a_i + 1:] for e in pair_edges.get(frozenset((a, b)), [])]
    o += [wrap(f"{e['source']} -{e['type']}-> {e['target']}: {e.get('logic', '')}", "          ") for e in found] \
        or ["          none"]
    o.append("    A8  NODES FORMED in the concept map (students/" + s["student"] + ".json):")
    if not nodes:
        o.append("          no node formed (the answer was stopped by a gate)")
    for cid, n in nodes.items():
        evc = {k2: len(v) for k2, v in (n.get("evidence") or {}).items() if v}
        mis = list((n.get("misconceptions") or {}).keys())
        if not n.get("observed"):
            o.append(f"          node [{cid}]  NOT ASSESSED - neighbour added to the map from the graph"
                     f" (prerequisite / parallel edge); inferred level {node_level(n.get('inferred_level'))}")
            continue
        o.append(f"          node [{cid}]  level {node_level(n.get('level'))}"
                 f"{'  (provisional)' if n.get('provisional') else ''}  observed (assessed from this answer)")
        o.append(wrap(f"evidence {', '.join(f'{k2}:{v}' for k2, v in evc.items()) or 'none'}; misconceptions held "
                      f"{', '.join(mis) or 'none'}; inferred level {node_level(n.get('inferred_level'))}; "
                      f"uncertain toward {n.get('uncertain_toward')}; stop reason: {n.get('stop_reason')}", "              "))
        for ek in ("E1", "E2", "E3", "E4"):
            for it in (n.get("evidence") or {}).get(ek, [])[:2]:
                o.append(wrap(f"{ek}: \"{it.get('clause', '')[:70]}\" -> \"{it.get('statement', '')[:110]}\" "
                              f"({it.get('score')})", "                  "))
    if student.get("gaps"):
        o.append(wrap("gaps (prerequisites flagged): " + json.dumps(student["gaps"], ensure_ascii=False)[:300], "          "))
    node_edges = [e for a_i, a in enumerate(list(nodes)) for b in list(nodes)[a_i + 1:]
                  for e in pair_edges.get(frozenset((a, b)), [])]
    o.append(wrap("=> FINAL CONCEPT MAP: nodes " + (", ".join(f"{cid} [{node_level(n.get('level')) if n.get('observed') else 'not assessed'}]" for cid, n in nodes.items())
                                                    or "none") + "; edges "
                  + ("; ".join(f"{e['source']}-{e['type']}->{e['target']}" for e in node_edges) or "none between them")
                  + f"; drawn in maps/{s['student']}.html", "    "))

    # B level
    o += ["", "  WORKFLOW B - LEVEL"]
    o.append("    B1  gates: " + (", ".join(s["prompt_gates"]) + " -> stopped" if s["prompt_gates"] else "none -> continue"))
    o.append("    B2  graph evidence (clause -> graph statement, check, score, status, level way):")
    ev = [(c["concept"], e) for c in s["concepts"] for e in c.get("evidence", [])
          if not e["statement"].startswith("confirmed by the run") and e["check"] not in ("wrong_trace", "own_run")]
    o += [wrap(f"{cc} {e['check']}: \"{e['clause'][:80]}\" -> \"{e['statement'][:120]}\" ({e['score']}, "
               f"{e['status']}, {e.get('way') or '-'})", "          ") for cc, e in ev] or ["          none"]
    o.append("    B3  code run:")
    o.append(wrap("run output: " + (str(s.get("run_output"))[:300] if s.get("run_output") else "(not run)"), "          "))
    facts = [e["statement"] for c in s["concepts"] for e in c.get("evidence", [])
             if e["statement"].startswith("confirmed by the run") or e["check"] in ("wrong_trace", "own_run")
             or (e["check"] == "held" and "match a run" in e["statement"])]
    o += [wrap(f, "          ") for f in dict.fromkeys(facts)] or ["          no claim of the answer could be checked by the run"]
    o.append("    B4  rule level per concept (ladder walk over E1-E4, stored on the node):")
    o += [wrap(f"{c['concept']}: {c.get('level') or '-'} - {c.get('stop_reason', '')}", "          ") for c in linked]
    beyond = asks_beyond(asked, code)
    o.append(wrap(f"B5  LLM judge (original prompt) on: {', '.join(names)}"
                  + ("; the prompt also said the part goes beyond the given code (an L4 way)" if beyond else ""), "    "))
    for c in s["concepts"]:
        j = c.get("judge") if isinstance(c.get("judge"), dict) else None
        if not j:
            continue
        lv, way = j.get("level"), j.get("way") or ""
        o.append(f"          [{c['concept']}] -> {lv} via '{way or '-'}' (correct={j.get('correct')})")
        o.append(wrap(f"quote \"{j.get('quote', '')}\"; reason: {j.get('why', '')}", "              "))
        if lv in LV[:5]:
            logic, ws, note = ex.level_logic(c["concept"], lv, way)
            if logic:
                o.append(wrap(f"edge {c['concept']} -has_level-> {c['concept']}@{lv}: {logic}", "              "))
            if note:
                o.append(wrap(f"note: {note}", "              "))
            for w in ws[:2]:
                o.append(wrap(f"way {w.get('way')} [{w.get('rule_type')}]: {w.get('edge_logic') or w.get('exact_rule', '')}", "              "))
    o.append("    B6  fusion per concept (rule level -> fused level, the step that set it):")
    for c in s["concepts"]:
        if not c.get("assessed"):
            o.append(f"          {c['concept']}: not assessed ({c.get('stop_reason', '')[:60]})")
            continue
        o.append(f"          {c['concept']}: {c.get('level') or '-'} -> {c['prompt_level']}  (set by {c.get('level_source') or '-'}"
                 f"{', wrong rule' if c.get('wrong_rule') else ''})")
    assessed = [c for c in s["concepts"] if c.get("assessed")]
    wrong = [c["concept"] for c in assessed if c.get("wrong_rule")]
    rule = (f"a concept holds a wrong rule ({', '.join(wrong)}) -> L0" if wrong
            else f"highest concept level -> {s['max_level'] or 'none'}")
    o.append(wrap(f"B7  answer level: {rule}", "    "))
    o.append(f"    => FINAL LEVEL: {s['max_level'] or 'none'}   (classified level: {label})")
    return o


if __name__ == "__main__":
    main()
